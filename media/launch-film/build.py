"""Write the scene windows into index.html, the burned-in subtitles into compositions/subs.html and the whole
narration as captions into renders/photo-checker-v1.en.vtt.

    python3 -I build.py
    node scripts/build-icons.mjs .      # the HIG Native glyph sprite (only when the icon list changes)

Each scene host's data-start/data-duration and the root duration come from the same numbers the scenes read at
runtime (window.TM in assets/timing.js, sound/timing.json), so the two can never drift apart. The subtitle cues are
cut from the narration's own word times (narration/words.json -> assets/vo.js): a re-voiced or re-slotted line
re-times its subtitles here, and the scenes re-time themselves through the W() helper.
"""
import html, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TM = json.loads((ROOT / "sound/timing.json").read_text())
vo_js = (ROOT / "assets/vo.js").read_text()
VO = json.loads(vo_js[vo_js.index("{"): vo_js.rindex("}") + 1])
HOSTS = {"s1-hook": "s1", "s2-title": "s2", "s3-board": "s3", "s4-proof": "s4", "s5-end": "s5"}
r = lambda x: f"{x:.3f}".rstrip("0").rstrip(".")

# Subtitle cues (compositions/subs.html, one layer over the scenes): at most 2 lines of 42 characters. Lines shown big on screen are not subtitled: v01 (the hook's
# question), v03 (the title) and v13 (the end card wordmark). Each chunk must be the next words of its line, in order.
SUBS = [
    ("v02", "And with two people in frame,\nwhich face is it about?"),
    ("v04", "A small client encodes the photo\nand posts it to API Gateway."),
    ("v05", "The gateway hands it\nto a Lambda function."),
    ("v06", "It asks Amazon Rekognition\nto describe the faces it finds."),
    ("v07", "Unless there is exactly one, it answers:"),
    ("v07", "please upload a picture\nwith only one face."),
    ("v08", "One face passes only if it's smiling\nand its eyes are open."),
    ("v09", "Anything else comes back\nas a bad profile photo."),
    ("v10", "Its role allows three log actions\nand read-only Rekognition, nothing else."),
    ("v11", "Fourteen Terraform resources build\nall of it, and terraform validate passes."),
    ("v12", "It builds on an AWS example, adding\nthe one-face check and the photo rule."),
]
LEAD, TAIL, GAP = 0.08, 0.30, 0.04
# The caption file (renders/photo-checker-v1.en.vtt) carries the whole narration: the burned-in cues plus the three
# lines shown big on screen.
ON_SCREEN = [("v01", "One question:\nis this usable as a profile photo?"),
             ("v03", "This is the serverless\nprofile-photo checker."),
             ("v13", "Serverless profile-photo checker.")]
VTT = sorted(SUBS + ON_SCREEN, key=lambda c: int(c[0][1:]))   # stable: chunks of one line keep their order


def cues(items=SUBS):
    pos, out = {}, []
    for k, text in items:
        n = len(text.split())
        words = VO[k]["words"][pos.get(k, 0): pos.get(k, 0) + n]
        got = " ".join(w["w"] for w in words)
        assert got == " ".join(text.split()), f"{k}: subtitle words {text!r} do not match the narration {got!r}"
        for line in text.split("\n"):
            assert len(line) <= 42, f"{k}: subtitle line over 42 characters: {line!r}"
        pos[k] = pos.get(k, 0) + n
        out.append([words[0]["t0"] - LEAD, words[-1]["t1"] + TAIL, text])
    for a, b in zip(out, out[1:]):
        a[1] = min(a[1], b[0] - GAP)
    return out


if not (ROOT / "index.html").exists():
    raise SystemExit("build.py: no index.html yet")
s = (ROOT / "index.html").read_text()
for host, key in HOSTS.items():
    a, b = TM[key]
    s, n = re.subn(rf'(<div id="{host}"[^>]*?data-start=")[^"]*(" data-duration=")[^"]*(")', rf"\g<1>{r(a)}\g<2>{r(b - a)}\g<3>", s)
    assert n == 1, host
s, n = re.subn(r'(<div id="main"[^>]*?data-duration=")[^"]*(")', rf"\g<1>{r(TM['duration'])}\g<2>", s); assert n == 1
s, n = re.subn(r'(<audio id="soundtrack"[^>]*?data-duration=")[^"]*(")', rf"\g<1>{r(TM['duration'])}\g<2>", s); assert n == 1
s, n = re.subn(r'(<div id="subtitles"[^>]*?data-duration=")[^"]*(")', rf"\g<1>{r(TM['duration'])}\g<2>", s); assert n == 1
(ROOT / "index.html").write_text(s)

C = cues()
subs = ROOT / "compositions/subs.html"
block = "<!-- HF:SUBS (generated by build.py from window.VO, do not hand-edit) -->\n" + "".join(
    f'    <div id="sub-{i}" class="sub" data-t0="{r(a)}" data-t1="{r(b)}">{html.escape(t, quote=False).replace("'", "’")}</div>\n'
    for i, (a, b, t) in enumerate(C, 1)) + "    <!-- /HF:SUBS -->"
t, n = re.subn(r"<!-- HF:SUBS[\s\S]*?<!-- /HF:SUBS -->", lambda m: block, subs.read_text()); assert n == 1
subs.write_text(t)
def ts(x):
    ms = int(round(max(0.0, x) * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d}.{ms % 1000:03d}"


V = cues(VTT)
(ROOT / "renders").mkdir(exist_ok=True)
(ROOT / "renders/photo-checker-v1.en.vtt").write_text("WEBVTT\n\n" + "".join(
    f"{i}\n{ts(a)} --> {ts(b)}\n{t}\n\n" for i, (a, b, t) in enumerate(V, 1)))
print("index.html:", ", ".join(f"{k} {TM[k][0]}-{TM[k][1]}" for k in HOSTS.values()), f"| {TM['duration']} s | subs.html: {len(C)} cues | renders/photo-checker-v1.en.vtt: {len(V)} cues")
